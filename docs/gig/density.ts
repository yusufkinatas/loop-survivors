// Regenerates docs/gig/density.md.
//
//   npx tsx docs/gig/density.ts > docs/gig/density.md
//
// The sibling of docs/baseline/density.ts, and it has to be a different tool
// rather than the same one pointed at a new branch. That tool derives every
// number from the shipped four-rung ladders, and under The Gig there are no
// shipped patterns: a build is a set of performances. So what is derivable here
// is the ROOM the tape gives the player — the ceiling, the floor, and the shape
// of what a single recording pass can ask for — and the actual densities have to
// come off played runs and the capture set.
//
// Everything below is read straight out of src/, so it follows the branch.

import { TAPE_LADDER } from '../../src/game/gig/tape';
import { GIG_SECTIONS, GIG_LENGTH_S } from '../../src/game/gig/songs';
import { SOUNDSET_LADDERS } from '../../src/audio/ladders/house';
import { PALETTE_ROLES, PALETTE_SEATS } from '../../src/audio/kits';
import { chartStageForLevel, WEAPON_MAX_LEVEL } from '../../src/game/weapons/levels';
import { BUILD, xpForNextLevel } from '../../src/game/config';
import type { Role } from '../../src/audio/kits';

const STEPS = 16;
const CAP = BUILD.weaponCap;

const LADDER_ROLES = PALETTE_ROLES.filter((role) => SOUNDSET_LADDERS[role] !== undefined);
const PERFORMABLE = LADDER_ROLES.filter(
  (role) => !(PALETTE_SEATS.texture as readonly Role[]).includes(role),
);

const controlPerBar = (role: Role, level: number): number => {
  const chart = SOUNDSET_LADDERS[role]![chartStageForLevel(level) - 1];
  return chart.events.length / chart.bars;
};

const out: string[] = [];
const say = (line = ''): void => out.push(line);

say('# The Gig: what the tape allows');
say();
say('Generated by `npx tsx docs/gig/density.ts`. Read straight out of');
say('`src/game/gig/tape.ts` and `src/game/gig/songs.ts` — nothing here is');
say('hand-maintained.');
say();
say('> **Trigger** — one musical-grid event with two outputs: a sound in the mix');
say('> and one attack in the world. Density is triggers per bar. A **bar** is the');
say('> few-second musical measure the loop is built from — and in this branch a bar');
say('> lasts three different lengths, because the three songs run at three tempos.');
say();
say('This is deliberately NOT the same table as');
say('[`docs/baseline/density.md`](../baseline/density.md). That one derives every');
say('density from the shipped');
say('four-rung ladders. Under The Gig nobody authored your pattern, so there is no');
say('density to derive: what is derivable is the **room** the tape gives you, and the');
say('rest has to be measured off played runs and the capture set.');
say();

// ---------------------------------------------------------------------------
say('## The tape ladder');
say();
say('| rung | bars | hits (ceiling) | triggers/bar at full | taps this pass asks for |');
say('|---|---|---|---|---|');
for (let level = 1; level <= WEAPON_MAX_LEVEL; level++) {
  const rung = TAPE_LADDER[level - 1];
  const previous = level > 1 ? TAPE_LADDER[level - 2] : null;
  // Growing the loop COPIES what is already on the tape into the new bars, so a
  // rung only ever asks for the difference.
  const carried = previous ? previous.hits * (rung.bars / previous.bars) : 0;
  const asks = level === 1 ? rung.hits : Math.max(0, rung.hits - carried);
  say(
    `| ${level} | ${rung.bars} | ${rung.hits} | ${(rung.hits / rung.bars).toFixed(2)} | ` +
    `${asks}${level === 1 ? ' (a fresh take)' : ''} |`,
  );
}
say();

const perBar = TAPE_LADDER.map((r) => r.hits / r.bars);
const falls = perBar.map((v, i) => (i > 0 && v < perBar[i - 1] ? i + 1 : 0)).filter(Boolean);
say(falls.length === 0
  ? '**No rung thins a track out.** Per-bar density climbs ' +
    perBar.map((v) => v.toFixed(2)).join(' → ') +
    ' and never falls, so a level-up is never a trap. Every fall in density a run\n' +
    'shows is therefore the player\'s own choice — which is exactly what the hard\n' +
    'floor (#256) asks a stack to be able to produce.'
  : `**A rung thins out at ${falls.join(', ')}** — a level-up that makes a track sparser is a trap. Fix the ladder.`);
say();

const totalTaps = TAPE_LADDER.reduce((sum, rung, i) => {
  const previous = i > 0 ? TAPE_LADDER[i - 1] : null;
  const carried = previous ? previous.hits * (rung.bars / previous.bars) : 0;
  return sum + (i === 0 ? rung.hits : Math.max(0, rung.hits - carried));
}, 0);
say(`**A track's whole life costs ${totalTaps} taps**, spread over ${WEAPON_MAX_LEVEL} short passes.`);
say('That is the point of copying the existing take into new bars: it keeps this an');
say('overdubbing session rather than a button-mashing test. The one place execution');
say(`genuinely costs is a voluntary re-cut at the top, which asks for all ${TAPE_LADDER[WEAPON_MAX_LEVEL - 1].hits} in a`);
say('single loop.');
say();

// ---------------------------------------------------------------------------
say('## The ceiling, against the control');
say();
const gigCeiling = perBar[WEAPON_MAX_LEVEL - 1] * CAP;
const densest = [...PERFORMABLE].sort((a, b) => controlPerBar(b, 8) - controlPerBar(a, 8)).slice(0, CAP);
const sparsest = [...PERFORMABLE].sort((a, b) => controlPerBar(a, 8) - controlPerBar(b, 8)).slice(0, CAP);
const sum = (roles: readonly Role[]): number => roles.reduce((t, r) => t + controlPerBar(r, 8), 0);
const REFERENCE: readonly Role[] = ['kick', 'bass', 'hat', 'chord', 'lead'];
say('| build | triggers/bar |');
say('|---|---|');
say(`| control, \`07-maxed-five\` (${REFERENCE.join(', ')}) at VIII | ${sum(REFERENCE).toFixed(2)} |`);
say(`| The Gig, ${CAP} tracks maxed and **every hit budget filled** | ${gigCeiling.toFixed(2)} |`);
say(`| control, densest ${CAP} at VIII (${densest.join(', ')}) | ${sum(densest).toFixed(2)} |`);
say(`| control, sparsest ${CAP} at VIII (${sparsest.join(', ')}) | ${sum(sparsest).toFixed(2)} |`);
say();
say(`The Gig's ceiling was aimed at the control's reference maxed build (${sum(REFERENCE).toFixed(2)}/bar,`);
say('the point `docs/baseline/` and `docs/palette-control/` both call `07-maxed-five`)');
say('and it lands just above it. The control can go far denser than either — pick the');
say(`five busiest voices and it fires ${sum(densest).toFixed(2)} a bar — and that ceiling is not the`);
say('interesting number anyway.');
say();
say('**The interesting number is the floor.** The control\'s sparsest maxed build');
say(`fires ${sum(sparsest).toFixed(2)}/bar and that is a floor a player cannot get below: the only lever`);
say('on density is refusing level-ups, which costs damage and buys nothing you can');
say(`hear. The Gig's floor is **${CAP}.00/bar** — one hit a bar per track — and it is`);
say('reachable at any moment by re-cutting, for the price of the valley. That gap is');
say('the whole of what this stack is for.');
say();

// ---------------------------------------------------------------------------
say('## Where the density can go that the control\'s cannot');
say();
say('A tape is up to four bars long and the hits may sit anywhere on it, so a build');
say('can put its whole budget in one bar of the phrase. The control cannot: every');
say('authored rung is either one bar (identical every bar) or written to fill its');
say('bars evenly.');
say();
const top = TAPE_LADDER[WEAPON_MAX_LEVEL - 1];
say('| shape of a maxed track | bar 1 | bar 2 | bar 3 | bar 4 | mean |');
say('|---|---|---|---|---|---|');
const spread = Math.floor(top.hits / top.bars);
say(`| spread evenly | ${spread} | ${spread} | ${spread} | ${top.hits - spread * 3} | ${(top.hits / top.bars).toFixed(2)} |`);
say(`| front-loaded | ${Math.min(STEPS, top.hits)} | ${Math.max(0, Math.min(STEPS, top.hits - STEPS))} | 0 | 0 | ${(top.hits / top.bars).toFixed(2)} |`);
say();
say('Same mean, and a completely different four bars. The mean is what a density');
say('table can see; the difference between those two rows is what a loudness meter');
say('sees. `docs/baseline/` measured loudness range at 0.4–0.6 LU at every point and');
say('`docs/palette-control/` measured 0.3–0.7 LU, both concluding there are no peaks');
say('at any scale.');
say();
say('**MEASURED, and it is the finding of this branch.** An evenly-spread maxed');
say('build reads **0.5 LU** — exactly where the control has always sat. A');
say('front-loaded phrase reads **8.7 LU**, fourteen times the hard floor, and it');
say('does not even need the full budget to get there. The numbers and what they do');
say('and do not prove are in [`README.md`](README.md).');
say();

// ---------------------------------------------------------------------------
say('## The set list');
say();
say('| section | from | to | tempo | shuffle | draws heavier on |');
say('|---|---|---|---|---|---|');
for (const section of GIG_SECTIONS) {
  say(
    `| ${section.name}${section.label ? ` (${section.label})` : ''} | ${mmss(section.startS)} | ` +
    `${mmss(section.endS)} | ${section.bpm} | ${section.swing.toFixed(2)} | ` +
    `${section.favours.length ? section.favours.join(', ') : '—'} |`,
  );
}
say();
say(`The gig is **${mmss(GIG_LENGTH_S)}** long against the base's 30:00, and it ends on the`);
say('encore rather than on a clock.');
say();
say('A bar is a different length in each song, which changes what a take *is* without');
say('the take changing:');
say();
say('| tempo | one bar | a 4-bar loop | a maxed track\'s triggers/second |');
say('|---|---|---|---|');
for (const bpm of [95, 124, 140]) {
  const bar = (4 * 60) / bpm;
  say(`| ${bpm} | ${bar.toFixed(2)}s | ${(bar * 4).toFixed(2)}s | ${(perBar[7] / bar).toFixed(2)} |`);
}
say();
say('So the same tape fires 47% more often in song three than in song one. Per-trigger');
say('damage is scaled against tempo (`tempoComp`, docs/plan.md\'s own rule) so that is');
say('not a free damage buff — but nothing scales the *sound*, which is the point: a');
say('dense take that breathed at 95 is a blur at 140, and on a choking voice it is a');
say('stutter. That is where "genre-shaped strength" comes from here.');
say();

// ---------------------------------------------------------------------------
say('## The decision stream, and the back half');
say();
say('Inherited unchanged from the base, deliberately — it is the same bias in all');
say('five round-1 stacks (#265), so it does not corrupt the comparison.');
say();
let cumulative = 0;
let buildDoneAt = 0;
const totalLevels = CAP * WEAPON_MAX_LEVEL;
for (let level = 1; level <= 200; level++) {
  cumulative += xpForNextLevel(level);
  if (level >= totalLevels && buildDoneAt === 0) buildDoneAt = level;
}
say(`A full build is **${CAP} tracks × ${WEAPON_MAX_LEVEL} rungs = ${totalLevels} levels**, the same count the base has,`);
say('so it completes at the same place in the clock — around minute fourteen, which');
say('#265 measured at 13:27 and 14:42 on two seeds. On a 30-minute run that leaves the');
say(`back half with no decision in it. On a ${mmss(GIG_LENGTH_S)} gig it leaves the last three or`);
say('four minutes.');
say();
say('**And The Gig has something to do there that the base does not.** A re-cut is');
say('free and always available, so a maxed build\'s remaining decision is not *what to');
say('take* but *what to play* — which is the only answer to the dead back half that');
say('costs no new content.');
say();

console.log(out.join('\n'));

function mmss(seconds: number): string {
  const s = Math.round(seconds);
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
}
