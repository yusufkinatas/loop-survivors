// Regenerates docs/baseline/density.md from the shipped ladders.
//
//   npx tsx docs/baseline/density.ts > docs/baseline/density.md
//
// Everything here is read straight out of src/, so on a prototype branch this
// reports that branch's numbers and the two sets stay comparable.

import { SOUNDSET_LADDERS } from '../../src/audio/ladders/house';
import { chartStageForLevel, WEAPON_MAX_LEVEL } from '../../src/game/weapons/levels';
import { xpForNextLevel } from '../../src/game/config';
import { BUILD } from '../../src/game/config';

const ROLES = ['kick', 'clap', 'snare', 'hat', 'bass', 'chord', 'lead', 'arp'] as const;
type R = (typeof ROLES)[number];

const chartFor = (role: R, stage: number) => SOUNDSET_LADDERS[role]![stage - 1];
const perBar = (role: R, stage: number) => {
  const c = chartFor(role, stage);
  return c.events.length / c.bars;
};

const out: string[] = [];
const say = (line = '') => out.push(line);

say('# Trigger density, derived from the shipped ladders');
say();
say('Generated by `npx tsx docs/baseline/density.ts`. Every number is read from');
say('`src/audio/ladders/house.ts` and `src/game/weapons/levels.ts` — nothing here');
say('is hand-maintained.');
say();
say('A **trigger** is one musical-grid event: a sound in the mix and one attack in');
say('the world. Density is triggers per bar. The grid is 16 steps (16th notes) per');
say('bar; at this track\'s 122 BPM a bar lasts 1.97 seconds.');
say();

say('## Triggers per bar, by weapon level');
say();
say('| weapon | ' + Array.from({ length: WEAPON_MAX_LEVEL }, (_, i) => `L${i + 1}`).join(' | ') + ' | L1→L8 |');
say('|---|' + Array.from({ length: WEAPON_MAX_LEVEL }, () => '---').join('|') + '|---|');
for (const role of ROLES) {
  const cells = Array.from({ length: WEAPON_MAX_LEVEL }, (_, i) =>
    perBar(role, chartStageForLevel(i + 1)).toFixed(2),
  );
  const ratio = perBar(role, 4) / perBar(role, 1);
  say(`| ${role} | ${cells.join(' | ')} | ×${ratio.toFixed(2)} |`);
}
say();
say('Eight gameplay levels, four authored chart stages, banded two levels each');
say('(`chartStageForLevel`). **Levels 2, 4, 6 and 8 change damage and nothing that');
say('can be heard** — the density steps only at 3, 5 and 7.');
say();

say('## Every rung, per role');
say();
for (const role of ROLES) {
  const rungs = [1, 2, 3, 4].map((s) => {
    const c = chartFor(role, s);
    return `s${s}: ${c.events.length}ev/${c.bars}bar = ${(c.events.length / c.bars).toFixed(2)}`;
  });
  say(`- **${role}** — ${rungs.join(' · ')}`);
}
say();

say('## Does anything ever thin out?');
say();
const drops: string[] = [];
for (const role of ROLES) {
  for (let s = 2; s <= 4; s++) {
    if (perBar(role, s) < perBar(role, s - 1)) {
      drops.push(`- ${role}: stage ${s} (${perBar(role, s)}) < stage ${s - 1} (${perBar(role, s - 1)})`);
    }
  }
}
say(
  drops.length
    ? drops.join('\n')
    : '**No.** Across all eight roles and all four stages, no rung fires fewer\n' +
        'triggers per bar than the rung below it. There is no level-up anywhere in the\n' +
        'game that makes anything sparser.',
);
say();

function occupancy(roles: readonly R[], stage: number) {
  let total = 0;
  const steps = new Set<number>();
  for (const role of roles) {
    const c = chartFor(role, stage);
    total += c.events.length / c.bars;
    for (const ev of c.events) steps.add(ev.step % 16);
  }
  return { total, steps: steps.size };
}

say('## How full the bar gets');
say();
say('| all eight roles at | triggers/bar | grid steps used |');
say('|---|---|---|');
for (const stage of [1, 2, 3, 4]) {
  const o = occupancy(ROLES, stage);
  say(`| stage ${stage} | ${o.total.toFixed(2)} | ${o.steps}/16 |`);
}
say();
say(`A build holds **${BUILD.weaponCap} weapons** and **${BUILD.itemCap} passives**, so eight at once is`);
say('unreachable — but at the top stage the eight roles between them put something');
say('on every one of the sixteen steps. There is no empty slot left for an arrival.');
say();

say('## Real five-weapon builds');
say();
const byDensity = [...ROLES].sort((a, b) => perBar(b, 4) - perBar(a, 4)).slice(0, BUILD.weaponCap);
const bySparsity = [...ROLES].sort((a, b) => perBar(a, 4) - perBar(b, 4)).slice(0, BUILD.weaponCap);
const BANDS: Array<[string, readonly R[]]> = [
  ['densest possible', byDensity],
  ['sparsest possible', bySparsity],
];
say('| band | roles | all at L1 | all at L8 | growth | steps used at L8 |');
say('|---|---|---|---|---|---|');
for (const [label, roles] of BANDS) {
  const lo = occupancy(roles, 1);
  const hi = occupancy(roles, 4);
  say(
    `| ${label} | ${roles.join(', ')} | ${lo.total.toFixed(2)} | **${hi.total.toFixed(2)}** | ` +
      `×${(hi.total / lo.total).toFixed(2)} | ${hi.steps}/16 |`,
  );
}
say();
say('The sparsest maxed build the catalog permits is the floor on late-run density.');
say('A player who wants to strip back cannot get below it: the only lever on density');
say('is refusing level-ups, which costs damage and buys nothing musically.');
say();

say('## Level-up cadence');
say();
say('From `xpForNextLevel` (cloned from Vampire Survivors), so the decision stream\'s');
say('shape is fixed regardless of how any one run goes.');
say();
say('| reach level | XP for that step | cumulative XP |');
say('|---|---|---|');
let cum = 0;
const MARKS = new Set([2, 5, 10, 15, 20, 25, 30, 35, 40, 45, 50]);
for (let level = 1; level <= 50; level++) {
  cum += xpForNextLevel(level);
  if (MARKS.has(level + 1)) say(`| ${level + 1} | ${xpForNextLevel(level)} | ${cum} |`);
}
say();
say(
  `A full build is ${BUILD.weaponCap} weapons × ${WEAPON_MAX_LEVEL} levels + ${BUILD.itemCap} passives. ` +
    `Of the ${BUILD.weaponCap * WEAPON_MAX_LEVEL} weapon levels, only ` +
    `${BUILD.weaponCap * 3} move the music at all.`,
);

console.log(out.join('\n'));
